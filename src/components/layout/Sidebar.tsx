/** hover한 화면 Y좌표를 필이 화면 밖으로 잘리지 않게 보정 — 레일·사이드바가
 *  화면 최상단(top 0) 고정이라 clientY가 곧 컨테이너 좌표다 */
function clampHoverY(clientY: number): number {
  return Math.min(Math.max(clientY, 28), window.innerHeight - 28);
}

/*
 * CONTEXT
 * - Problem      : 접힌 사이드바의 여백·선택 탭·아이콘·작은 프로필이 참고 이미지와 다르다.
 * - Why          : 72px 레일을 기준으로 로고 40px, 60px 탐색 행, 프로필 48px와 비례 간격을 맞춘다.
 * - Alternatives : 이미지 자체를 배경으로 쓰면 검색·프로필·펼치기 동작을 제공할 수 없다.
 * - Trade-offs   : 레일 브랜드 색상과 아이콘 윤곽을 참고 이미지 기준으로 고정한다.
 * - Edge Case    : 키보드 포커스와 기존 메뉴 동작은 유지하며 화면이 낮아도 탐색 행은 축소하지 않는다.
 */
/** 레일 네비 항목 — 아이콘 + 하단 라벨, active면 Main Blue 0.25 배경 + 좌측 액센트 탭 */
function CollapsedRail({ onExpand, onExpandToSearch, onOpenArchive, onOpenChat, isChatOpen, onFocusNode, onAddProject, workspaceTitle, meeting }: {
  onExpand: () => void;
  onExpandToSearch: () => void;
  onOpenArchive?: () => void;
  onOpenChat?: () => void;
  isChatOpen: boolean;
  onFocusNode: (id: string) => void;
  onAddProject: () => void;
  workspaceTitle: string;
  meeting: SidebarMeeting | null;
}) {
  const [hoverY, setHoverY] = useState<number | null>(null);
  const tree = useProjectTree('');
  const { nodes, edges, focusedNodeId } = useWorkspaceLayout();
  const selectedNodeId = focusedNodeId ?? nodes.find((node) => node.selected)?.id ?? null;
  return (
    <div className="relative flex h-full flex-col" onMouseLeave={() => setHoverY(null)} onMouseMove={(event) => setHoverY(clampHoverY(event.clientY))}>
      <button type="button" onClick={onExpand} aria-label="사이드바 펼치기" className="mx-auto mt-5"><OnNodeMark size={40} round /></button>
      <button type="button" onClick={onExpand} title={workspaceTitle} aria-label="워크스페이스 열기" className="mx-auto mt-4"><WorkspaceIcon name={workspaceTitle} size={38} /></button>
      <button type="button" onClick={onExpandToSearch} aria-label="검색" title="검색" className="mx-auto mt-4 flex size-10 items-center justify-center"><SidebarIcon name="search" width={27} /></button>
      <button type="button" onClick={onOpenChat} aria-label="AI 질문" aria-pressed={isChatOpen} title="AI 질문" className={`relative flex h-12 w-full items-center justify-center ${isChatOpen ? 'bg-main-blue-pale' : ''}`}>
        {isChatOpen && <span aria-hidden className="absolute top-1/2 left-0 h-[30px] w-[5px] -translate-y-1/2 rounded-r-[3px] bg-[#748dfd]" />}
        <SidebarIcon name="ai-chat" width={27} height={20} />
      </button>
      {meeting && <button type="button" onClick={() => onFocusNode(meeting.titleNodeId)} title={`회의 진행 중 · ${meeting.titleName}`} aria-label="회의 진행 중" className="mx-auto flex size-10 items-center justify-center text-red-500">●</button>}
      <div className="mx-3 my-2 border-t border-main-blue-pale" />
      <div className="flex min-h-0 flex-1 flex-col items-center gap-3 overflow-y-auto pt-2">
        {tree.map((project) => {
          const selected = selectedNodeId !== null && (project.id === selectedNodeId || getDescendantIds(project.id, edges).has(selectedNodeId));
          const color = figmaNodeColorOf(project.color)?.deep ?? project.color ?? 'rgb(var(--ds-main-blue))';
          return <button key={project.id} type="button" onClick={() => onFocusNode(project.id)} title={`${project.title} · 타이틀 ${project.count}개`} aria-label={project.title} aria-current={selected ? 'true' : undefined} className="flex size-8 shrink-0 items-center justify-center rounded-lg text-xs font-semibold text-white" style={{ backgroundColor: color, outline: selected ? '2px solid rgb(var(--ds-main-blue-deep))' : undefined }}>{project.title.charAt(0)}</button>;
        })}
        <button type="button" onClick={onAddProject} aria-label="프로젝트 노드 추가" title="프로젝트 노드 추가" className="flex size-8 shrink-0 items-center justify-center rounded-lg border border-dashed border-main-blue text-main-blue">+</button>
      </div>
      <SidebarHelp collapsed />
      <ProfileRow collapsed onOpenArchive={onOpenArchive} />
      {hoverY !== null && <HoverTogglePill y={hoverY} chevron="›" label="사이드바 펼치기" onActivate={onExpand} />}
    </div>
  );
}

/** 펼친 사이드바 우측 경계의 hover 감지 띠 — hover 위치에 접기 필을 띄운다.
 *  상시 토글 버튼(«)을 대체한다. 띠는 경계에 반씩 걸쳐 트리 스크롤 영역 가림을 최소화. */
function CollapseEdgeStrip({ onCollapse }: { onCollapse: () => void }) {
  const [hoverY, setHoverY] = useState<number | null>(null);

  return (
    <div
      className="absolute inset-y-0 -right-[5px] z-50 w-[10px]"
      onMouseLeave={() => setHoverY(null)}
    >
      <div
        className="h-full w-full"
        onMouseMove={(e) => setHoverY(clampHoverY(e.clientY))}
      />
      {hoverY !== null && (
        <HoverTogglePill
          y={hoverY}
          chevron="‹"
          label="사이드바 접기"
          onActivate={onCollapse}
        />
      )}
    </div>
  );
}

// ─── Sidebar 본체 ────────────────────────────────────────────────────────────

export default function Sidebar({
  isOpen,
  onToggle,
  onOpenArchive,
  onOpenChat,
  isChatOpen = false,
}: {
  isOpen: boolean;
  onToggle: () => void;
  onOpenArchive?: () => void;
  onOpenChat?: () => void;
  isChatOpen?: boolean;
}) {
  const {
    workspaceId,
    setWorkspaceId,
    setWorkspaceRole,
    setNodes,
    setEdges,
    setSynced,
    setFocusedNodeId,
    nodes,
    edges,
    meetings,
  } = useWorkspaceLayout();

  const sidebarMeeting = useMemo(() => pickSidebarMeeting(meetings, nodes), [meetings, nodes]);

  const [query, setQuery] = useState('');
  const [switcherOpen, setSwitcherOpen] = useState(false);
  const [newWsOpen, setNewWsOpen] = useState(false);
  const [settingsOpen, setSettingsOpen] = useState(false);
  const [workspaceTitle, setWorkspaceTitle] = useState('워크스페이스');
  const searchInputRef = useRef<HTMLInputElement>(null);
  const pendingSearchFocusRef = useRef(false);

  // 현재 워크스페이스 이름 — 목록 조회 결과에서 1회 확보
  useEffect(() => {
    if (!workspaceId) return;
    getWorkspaces()
      .then((list) => {
        const ws = list.find((w) => w.workspaceId === workspaceId);
        if (ws) setWorkspaceTitle(ws.title);
      })
      .catch(() => {});
  }, [workspaceId]);

  // ⌘K 검색 포커스 · ⌘\ 토글 — 전역 단축키 훅(#243) 도입 시 그쪽으로 이관.
  // e.key가 아니라 e.code(물리 키 위치) 비교인 이유: 한글 자판에서는 K 자리의
  // e.key가 'ㅏ'로 들어와 'k' 비교가 실패한다. IME 조합 중에는 'Process'가 되기도 함.
  useEffect(() => {
    const handler = (e: KeyboardEvent) => {
      if (!(e.metaKey || e.ctrlKey)) return;
      if (e.code === 'KeyK') {
        e.preventDefault();
        if (!isOpen) {
          pendingSearchFocusRef.current = true;
          onToggle();
        } else {
          searchInputRef.current?.focus();
        }
      } else if (e.code === 'Backslash') {
        e.preventDefault();
        onToggle();
      }
    };
    window.addEventListener('keydown', handler);
    return () => window.removeEventListener('keydown', handler);
  }, [isOpen, onToggle]);

  // 접힘 → ⌘K/검색 아이콘으로 펼친 직후 검색 인풋 포커스
  useEffect(() => {
    if (isOpen && pendingSearchFocusRef.current) {
      pendingSearchFocusRef.current = false;
      searchInputRef.current?.focus();
    }
  }, [isOpen]);

  const switchWorkspace = useCallback(
    (ws: Pick<WorkspaceListItem, 'workspaceId' | 'title' | 'role'>) => {
      // 그래프 상태를 비우고 재동기화 — layout의 sync effect가 새 workspaceId로 다시 fetch
      setNodes([]);
      setEdges([]);
      setFocusedNodeId(null);
      setWorkspaceId(ws.workspaceId);
      setWorkspaceRole(ws.role);
      setWorkspaceTitle(ws.title);
      setSynced(false);
    },
    [setNodes, setEdges, setFocusedNodeId, setWorkspaceId, setWorkspaceRole, setSynced],
  );

  const addProjectNode = useCallback(async () => {
    if (!workspaceId) return;
    // 기존 프로젝트들 아래쪽 빈 공간에 배치 후 카메라 이동(focus)
    const projectYs = nodes
      .filter((n) => (n.data as NodeData)?.isMain)
      .map((n) => n.position.y);
    const position = {
      x: 0,
      y: projectYs.length ? Math.max(...projectYs) + 240 : 0,
    };
    try {
      const colorPair = getRandomColorPair();
      const { nodeId } = await createProjectNode(workspaceId, '', position, {
        color: colorPair.bg,
        textColor: colorPair.text,
      });
      setNodes((prev) => [
        ...prev,
        {
          id: nodeId,
          type: 'textUpdater',
          position,
          data: {
            title: '',
            isMain: true,
            color: colorPair.bg,
            textColor: colorPair.text,
          },
        },
      ]);
      setFocusedNodeId(nodeId);
    } catch (err) {
      console.error('[Sidebar] createProjectNode failed', err);
    }
  }, [workspaceId, nodes, setNodes, setFocusedNodeId]);

  /*
   * CONTEXT
   * - Problem      : 시안의 프로젝트 행 + 버튼이 타이틀 생성 동작을 필요로 한다.
   * - Why          : 기존 API와 부모 색을 사용해 노드·엣지를 생성하고 REST 응답으로 상태를 반영한다.
   * - Alternatives : 캔버스 콜백을 전역 context에 추가하면 UI 전용 상태 계약이 늘어난다.
   * - Trade-offs   : 사이드바 생성은 오른쪽 배치를 기본으로 하며 캔버스에서 위치를 변경할 수 있다.
   * - Edge Case    : 워크스페이스나 부모가 없으면 중단하고 API 실패는 기존 로그 경로로 알린다.
   */
  const addTitleNode = async (parentId: string) => {
    if (!workspaceId) return;
    const parent = nodes.find((node) => node.id === parentId);
    if (!parent) return;
    const colorPair = getRandomColorPair();
    const color = (parent.data.color as string) || colorPair.bg;
    const textColor = (parent.data.textColor as string) || colorPair.text;
    const siblings = edges.filter((edge) => edge.source === parentId);
    const position = { x: parent.position.x + (parent.measured?.width ?? 200) + 100, y: parent.position.y + siblings.length * 70 };
    try {
      const { nodeId } = await createMdNode(workspaceId, '', position, { markdownBody: '', jsonBody: EMPTY_LEXICAL_JSON, color, textColor });
      setNodes((prev) => [...prev, { id: nodeId, type: 'textUpdater', position, data: { title: '', isMain: false, color, textColor, handleSide: 'right' } }]);
      const { edgeId } = await createEdge(workspaceId, parentId, nodeId, 'source-right', 'target-left');
      setEdges((prev) => [...prev, { id: edgeId, source: parentId, target: nodeId, type: 'branch', sourceHandle: 'source-right', targetHandle: 'target-left' }]);
      setNodes((prev) => applyDepthOnEdgeCreate(prev, [], parentId, nodeId));
      setFocusedNodeId(nodeId);
    } catch (error) {
      console.error('[Sidebar] createTitleNode failed', error);
    }
  };

  const focusNode = useCallback(
    (id: string) => {
      setNodes((previous) => previous.map((node) => ({ ...node, selected: node.id === id })));
      setFocusedNodeId(id);
    },
    [setFocusedNodeId, setNodes],
  );

  /*
   * CONTEXT
   * - Problem      : 폭만 애니메이션되고 내용은 펼침/레일이 즉시 교체돼, 좁은 폭에 펼침 내용이 끼워지며 툭 바뀌어 보였다.
   * - Why          : 두 레이어를 모두 고정 폭으로 띄워 두고 폭 전환 동안 교차 페이드한다. 펼칠 때는 폭이 먼저 늘고
   *                  내용이 뒤따라 나타나며, 접을 때는 내용이 먼저 사라진다. 내용은 줄바꿈되지 않고 그대로 드러난다.
   * - Alternatives : aside에 overflow-hidden으로 잘라 내기 → 폭 밖으로 펼쳐지는 워크스페이스 메뉴(303px)까지 잘린다.
   * - Trade-offs   : 두 레이어가 항상 마운트된다. 숨은 쪽은 inert로 포커스·클릭·스크린리더에서 빠진다.
   * - Edge Case    : ⌘K로 펼친 직후 검색 포커스는 inert가 풀린 뒤(같은 커밋 이후 effect)에 걸리므로 그대로 동작한다.
   */
  const layerClass = (visible: boolean) =>
    `absolute inset-y-0 left-0 flex flex-col transition-opacity ${
      visible ? 'opacity-100 duration-200 delay-100' : 'pointer-events-none opacity-0 duration-100'
    }`;

  return (
    <aside
      className={`sidebar-reference ${sidebarFont.className} fixed top-0 left-0 z-50 flex h-full flex-col bg-background transition-[width] duration-300 ease-[cubic-bezier(0.4,0,0.2,1)]`}
      style={{ width: isOpen ? SIDEBAR_WIDTH : RAIL_WIDTH }}
    >
      <div className={layerClass(isOpen)} style={{ width: SIDEBAR_WIDTH }} inert={!isOpen}>
          {/* 헤더 (X1·X6): On:Node 로고 행 + 워크스페이스 스위처 행 */}
          <div className="sidebar-header shrink-0">
            {/* 접기는 우측 경계 hover 필(CollapseEdgeStrip)·⌘\ 로 — 상시 버튼 없음 */}
            <div className="sidebar-brand-row">
              <div className="flex items-center gap-2"><OnNodeMark size={32} round /><OnNodeLogo /></div>
              <button type="button" onClick={onToggle} aria-label="사이드바 접기" title="사이드바 접기 ⌘\\" className="sidebar-collapse">
                <svg width="14" height="14" viewBox="0 0 20 20" fill="none" stroke="currentColor" strokeWidth="1.5"><path d="m10 4-6 6 6 6M16 4l-6 6 6 6" /></svg>
              </button>
            </div>
            <div className="relative">
              <button
                type="button"
                onClick={() => setSwitcherOpen((v) => !v)}
                aria-expanded={switcherOpen}
                aria-haspopup="menu"
                aria-controls={switcherOpen ? "workspace-switcher-menu" : undefined}
                className="sidebar-workspace flex w-full min-w-0 items-center text-left"
              >
                <WorkspaceIcon name={workspaceTitle} size={42} />
                <span className="min-w-0 truncate text-[16px] font-bold text-main-blue-deep">
                  {workspaceTitle}
                </span>
                <span className="sidebar-caret" aria-hidden="true" />
              </button>
              <WorkspaceSwitcher
                open={switcherOpen}
                currentId={workspaceId}
                onClose={() => setSwitcherOpen(false)}
                onSwitch={switchWorkspace}
                onNewWorkspace={() => setNewWsOpen(true)}
                onSettings={() => setSettingsOpen(true)}
              />
            </div>
          </div>

          {/* 노드 검색 (⌘K) */}
          <div className="sidebar-search-wrap shrink-0">
            <div className="sidebar-search flex items-center">
              <SidebarIcon name="search" width={27} />
              <input
                ref={searchInputRef}
                value={query}
                onChange={(e) => setQuery(e.target.value)}
                placeholder="검색"
                aria-label="노드 검색"
                className="min-w-0 flex-1 bg-transparent text-[13.4px] font-semibold text-[#4d4d4d] outline-none placeholder:text-[#4d4d4d]"
              />
            </div>
          </div>

          <button type="button" onClick={onOpenChat} aria-pressed={isChatOpen} className={`relative flex h-12 w-full shrink-0 items-center gap-3 px-6 text-left text-[13.4px] font-semibold text-[#4d4d4d] ${isChatOpen ? 'bg-main-blue-pale' : 'hover:bg-surface'}`}>
            {isChatOpen && <span aria-hidden className="absolute top-1/2 left-0 h-[30px] w-[5px] -translate-y-1/2 rounded-r-[3px] bg-[#748dfd]" />}
            <SidebarIcon name="ai-chat" width={27} height={20} /> AI 질문
          </button>

          {/* 회의 진행 중 카드 (Figma X9 · S1) — 검색창 바로 아래, 진행 중인 회의가 없으면 숨김 */}
          <div className="shrink-0 px-3 pb-1 empty:hidden">
            <MeetingBanner meeting={sidebarMeeting} onClick={focusNode} />
          </div>

          <ProjectTreeSection
            query={query}
            onAddProject={addProjectNode}
            onFocusNode={focusNode}
            onAddTitle={addTitleNode}
          />

          <SidebarHelp />
          <ProfileRow onOpenArchive={onOpenArchive} />

          <CollapseEdgeStrip onCollapse={onToggle} />
      </div>
      <div className={layerClass(!isOpen)} style={{ width: RAIL_WIDTH }} inert={isOpen}>
        <CollapsedRail
          onExpand={onToggle}
          onOpenChat={onOpenChat}
          isChatOpen={isChatOpen}
          onFocusNode={focusNode}
          onAddProject={addProjectNode}
          workspaceTitle={workspaceTitle}
          meeting={sidebarMeeting}
          onOpenArchive={onOpenArchive}
          onExpandToSearch={() => {
            pendingSearchFocusRef.current = true;
            onToggle();
          }}
        />
      </div>

      <NewWorkspaceModal
        open={newWsOpen}
        onClose={() => setNewWsOpen(false)}
        onCreated={(id, title) => {
          setNewWsOpen(false);
          switchWorkspace({ workspaceId: id, title, role: 'OWNER' });
        }}
      />

      <WorkspaceSettingsModal
        open={settingsOpen}
        workspaceId={workspaceId}
        onClose={() => setSettingsOpen(false)}
        onRenamed={(title) => {
          setWorkspaceTitle(title);
          setSettingsOpen(false);
        }}
        onDeleted={async () => {
          setSettingsOpen(false);
          // 삭제 후 남은 워크스페이스로 전환 (서버가 최소 1개 유지를 보장)
          try {
            const list = await getWorkspaces();
            const next =
              list.find((w) => w.workspaceId !== workspaceId) ?? list[0];
            if (next) switchWorkspace(next);
          } catch (err) {
            console.error('[Sidebar onDeleted] switch failed', err);
          }
        }}
      />
    </aside>
  );
}
